function toShape(points) {
  const lons = points.map(([lon]) => lon);
  const lats = points.map(([, lat]) => lat);
  return {
    points,
    minLon: Math.min(...lons),
    maxLon: Math.max(...lons),
    minLat: Math.min(...lats),
    maxLat: Math.max(...lats)
  };
}

const LAND_SHAPES = Object.values(LAND_OUTLINES).map(toShape);
const WATER_SHAPES = Object.values(WATER_OUTLINES).map(toShape);

/** 짝수-홀수 규칙으로 점이 다각형 안에 있는지 판정한다. */
function contains(shape, lon, lat) {
  if (lon < shape.minLon || lon > shape.maxLon || lat < shape.minLat || lat > shape.maxLat) return false;

  const { points } = shape;
  let inside = false;
  for (let i = 0, j = points.length - 1; i < points.length; j = i, i += 1) {
    const [xi, yi] = points[i];
    const [xj, yj] = points[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

export function isLand(lon, lat) {
  return LAND_SHAPES.some((shape) => contains(shape, lon, lat))
    && !WATER_SHAPES.some((shape) => contains(shape, lon, lat));
}
